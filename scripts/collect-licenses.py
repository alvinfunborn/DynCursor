"""Collect notices for the locked Windows dependency graph; no third-party code changes."""
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent


def collect():
    metadata = json.loads(subprocess.check_output([
        'cargo', 'metadata', '--locked', '--format-version', '1',
        '--filter-platform', 'x86_64-pc-windows-msvc'
    ], cwd=ROOT, encoding='utf-8'))
    packages = {p['id']: p for p in metadata['packages']}
    nodes = {n['id']: n for n in metadata['resolve']['nodes']}
    visited = set()

    def visit(key):
        if key in visited:
            return
        visited.add(key)
        for dependency in nodes[key]['dependencies']:
            visit(dependency)

    visit(metadata['resolve']['root'])
    lines = ['DynCursor — Third-party Rust component licenses',
             'Generated by scripts/collect-licenses.py from Cargo.lock.',
             'Target: x86_64-pc-windows-msvc. Includes build dependencies.',
             'SPDX expressions below are upstream declarations. For OR licenses,',
             'the included texts are alternatives; AND notices remain applicable.',
             'Historical cursor artwork is documented separately in THIRD_PARTY_NOTICES.md.', '']
    missing = []
    for key in sorted(visited, key=lambda key: (packages[key]['name'], packages[key]['version'])):
        package = packages[key]
        if not package['source']:
            continue
        directory = pathlib.Path(package['manifest_path']).parent
        lines += ['=' * 76, f"{package['name']} {package['version']}",
                  f"Declared license: {package['license'] or 'not specified'}",
                  f"Authors: {', '.join(package['authors']) or 'See upstream source'}",
                  f"Repository: {package['repository'] or package['homepage'] or 'See crates.io'}",
                  f"Source: https://crates.io/crates/{package['name']}/{package['version']}", '']
        candidates = set()
        for path in directory.iterdir():
            if path.is_file() and path.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'COPYRIGHT', 'NOTICE', 'UNLICENSE')):
                candidates.add(path)
            elif path.is_dir() and path.name.lower() in ('licenses', 'license'):
                candidates.update(p for p in path.rglob('*') if p.is_file())
        if package['license_file']:
            candidates.add(directory / package['license_file'])
        supplement = ROOT / 'licenses' / f"{package['name']}-{package['version']}"
        if supplement.is_dir():
            candidates.update(p for p in supplement.iterdir() if p.is_file())
        if not candidates:
            missing.append(f"{package['name']} {package['version']}: {package['license']}")
            lines += ['The published crate contains no license text. The expression above',
                      'is its Cargo metadata declaration; no upstream notice was invented.', '']
        for path in sorted(candidates):
            if not path.is_file():
                continue
            text = path.read_text(encoding='utf-8', errors='replace')
            lines += [f'--- {path.name} ---', text.strip(), '']
    (ROOT / 'THIRD_PARTY_LICENSES.txt').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Collected {len(visited)-1} dependency packages.')
    if missing:
        print('Crates without supplied license texts:\n' + '\n'.join(missing))


if __name__ == '__main__':
    collect()
